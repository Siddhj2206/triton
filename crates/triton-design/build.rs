//! Generates Rust constants from `tokens.json`, the design canvas's token file.
//!
//! `tokens.json` is the single source of every design value. This script turns it
//! into `$OUT_DIR/tokens.rs`, which `src/lib.rs` includes. The struct definitions
//! live in the crate, so a role that is missing from the JSON, or one the crate does
//! not know, fails the build instead of drifting.

use std::fmt::Write as _;
use std::{env, fs, path::Path};

use serde_json::Value;

fn main() {
    let src = Path::new(env!("CARGO_MANIFEST_DIR")).join("tokens.json");
    println!("cargo::rerun-if-changed={}", src.display());
    let text = fs::read_to_string(&src).expect("read tokens.json");
    let t: Value = serde_json::from_str(&text).expect("tokens.json is valid JSON");

    let mut out = String::from("// Generated by build.rs from tokens.json. Do not edit.\n\n");
    schemes(&t, &mut out);
    state_layer(&t, &mut out);
    shape(&t, &mut out);
    space_and_size(&t, &mut out);
    type_scale(&t, &mut out);
    materials(&t, &mut out);
    elevation(&t, &mut out);
    motion(&t, &mut out);

    let out_dir = env::var("OUT_DIR").expect("OUT_DIR is set by cargo");
    fs::write(Path::new(&out_dir).join("tokens.rs"), out).expect("write tokens.rs");

    let codepoints = Path::new(env!("CARGO_MANIFEST_DIR")).join("fonts/symbols.codepoints");
    println!("cargo::rerun-if-changed={}", codepoints.display());
    let list = fs::read_to_string(&codepoints).expect("read fonts/symbols.codepoints");
    fs::write(Path::new(&out_dir).join("icons.rs"), icons(&list)).expect("write icons.rs");
}

/// The `Icon` enum from `fonts/symbols.codepoints` (written by `mise run fonts`).
fn icons(list: &str) -> String {
    let entries: Vec<(String, String, u32)> = list
        .lines()
        .filter(|l| !l.trim().is_empty() && !l.starts_with('#'))
        .map(|l| {
            let (name, cp) = l.split_once(' ').expect("`name codepoint` per line");
            let cp = u32::from_str_radix(cp.trim(), 16).expect("hex codepoint");
            let variant: String = name
                .split('_')
                .map(|w| {
                    let mut c = w.chars();
                    c.next().map_or_else(String::new, |f| {
                        f.to_ascii_uppercase().to_string() + c.as_str()
                    })
                })
                .collect();
            (name.to_owned(), variant, cp)
        })
        .collect();

    let mut out = String::from(
        "// Generated by build.rs from fonts/symbols.codepoints. Do not edit.\n\n\
         /// A Material Symbols icon. The list is `fonts/icons.txt`; add a name there and\n\
         /// run `mise run fonts`.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n\
         pub enum Icon {\n",
    );
    for (_, v, _) in &entries {
        writeln!(out, "    {v},").unwrap_or_default();
    }
    out.push_str("}\n\n");
    let n = entries.len();
    writeln!(out, "const CODEPOINTS: [char; {n}] = [").unwrap_or_default();
    for (_, _, cp) in &entries {
        writeln!(out, "    '\\u{{{cp:x}}}',").unwrap_or_default();
    }
    writeln!(out, "];\n\nconst NAMES: [&str; {n}] = [").unwrap_or_default();
    for (name, _, _) in &entries {
        writeln!(out, "    {name:?},").unwrap_or_default();
    }
    writeln!(
        out,
        "];\n\nimpl Icon {{\n    pub const ALL: [Icon; {n}] = ["
    )
    .unwrap_or_default();
    for (_, v, _) in &entries {
        writeln!(out, "        Icon::{v},").unwrap_or_default();
    }
    out.push_str(
        "    ];\n\n\
         /// The glyph to draw, in the Triton Symbols fonts.\n\
         pub const fn codepoint(self) -> char {\n        CODEPOINTS[self as usize]\n    }\n\n\
         /// The Material Symbols name.\n\
         pub const fn name(self) -> &'static str {\n        NAMES[self as usize]\n    }\n}\n",
    );
    out
}

fn get<'a>(v: &'a Value, path: &str) -> &'a Value {
    path.split('.').fold(v, |v, key| {
        v.get(key)
            .unwrap_or_else(|| panic!("tokens.json: missing `{path}` (at `{key}`)"))
    })
}

fn num(v: &Value, path: &str) -> f64 {
    get(v, path)
        .as_f64()
        .unwrap_or_else(|| panic!("tokens.json: `{path}` is not a number"))
}

fn text<'a>(v: &'a Value, path: &str) -> &'a str {
    get(v, path)
        .as_str()
        .unwrap_or_else(|| panic!("tokens.json: `{path}` is not a string"))
}

fn object<'a>(v: &'a Value, path: &str) -> &'a serde_json::Map<String, Value> {
    get(v, path)
        .as_object()
        .unwrap_or_else(|| panic!("tokens.json: `{path}` is not an object"))
}

/// `#RRGGBB` to a `Color` literal.
fn hex(s: &str) -> String {
    let h = s.trim().trim_start_matches('#');
    assert!(h.len() == 6, "tokens.json: `{s}` is not #RRGGBB");
    let c = |i: usize| u8::from_str_radix(&h[i..i + 2], 16).expect("hex digit");
    format!("Color::from_rgb8({}, {}, {})", c(0), c(2), c(4))
}

/// CSS `rgb(R G B / A)` to a `Color` literal.
fn css_rgb(s: &str) -> String {
    let inner = s
        .trim()
        .strip_prefix("rgb(")
        .and_then(|s| s.strip_suffix(')'))
        .unwrap_or_else(|| panic!("tokens.json: `{s}` is not rgb(R G B / A)"));
    let (rgb, alpha) = inner.split_once('/').unwrap_or((inner, "1"));
    let c: Vec<u8> = rgb
        .split_whitespace()
        .map(|n| n.parse().expect("rgb channel is 0..=255"))
        .collect();
    assert!(c.len() == 3, "tokens.json: `{s}` needs three channels");
    let a: f32 = alpha.trim().parse().expect("alpha is a number");
    format!("Color::from_rgba8({}, {}, {}, {a:?})", c[0], c[1], c[2])
}

fn f(x: f64) -> String {
    format!("{:?}", x as f32)
}

fn schemes(t: &Value, out: &mut String) {
    for (name, konst) in [("dark", "DARK"), ("light", "LIGHT")] {
        writeln!(out, "pub(crate) const {konst}: Scheme = Scheme {{").unwrap_or_default();
        for (role, value) in object(t, &format!("color.{name}")) {
            let v = value.as_str().expect("color role is a string");
            writeln!(out, "    {role}: {},", hex(v)).unwrap_or_default();
        }
        out.push_str("};\n\n");
    }
}

fn state_layer(t: &Value, out: &mut String) {
    out.push_str("pub(crate) const STATE_LAYER: StateLayer = StateLayer {\n");
    for key in [
        "hover",
        "focus",
        "press",
        "drag",
        "disabled_content",
        "disabled_container",
    ] {
        writeln!(
            out,
            "    {key}: {},",
            f(num(t, &format!("state_layer.{key}")))
        )
        .unwrap_or_default();
    }
    out.push_str("};\n\n");
}

fn shape(t: &Value, out: &mut String) {
    writeln!(
        out,
        "pub(crate) const CORNER_SMOOTHING: f32 = {};",
        f(num(t, "shape.corner_smoothing"))
    )
    .unwrap_or_default();
    out.push_str("pub(crate) const RADII: Radii = Radii {\n");
    for key in [
        "tiled",
        "xs",
        "sm",
        "md",
        "lg",
        "xl",
        "full",
        "floating_window",
        "list_outer",
        "list_inner",
        "connected_end",
        "connected_inner",
    ] {
        writeln!(out, "    {key}: {},", f(num(t, &format!("shape.{key}")))).unwrap_or_default();
    }
    out.push_str("};\n\n");
    writeln!(
        out,
        "pub(crate) const WAVE_LOBES: u32 = {};",
        num(t, "shape.wave.lobes") as u32
    )
    .unwrap_or_default();
    writeln!(
        out,
        "pub(crate) const WAVE_PATH: &str = {:?};\n",
        text(t, "shape.wave.path")
    )
    .unwrap_or_default();
}

fn space_and_size(t: &Value, out: &mut String) {
    let space: Vec<String> = get(t, "space")
        .as_array()
        .expect("space is an array")
        .iter()
        .map(|v| f(v.as_f64().expect("space step is a number")))
        .collect();
    writeln!(
        out,
        "pub(crate) const SPACE: [f32; {}] = [{}];\n",
        space.len(),
        space.join(", ")
    )
    .unwrap_or_default();

    let pair = |path: &str| {
        let a = get(t, path).as_array().expect("pair is an array");
        format!(
            "({}, {})",
            f(a[0].as_f64().expect("number")),
            f(a[1].as_f64().expect("number"))
        )
    };
    let n = |path: &str| f(num(t, path));
    writeln!(
        out,
        "pub(crate) const SIZE: Size = Size {{\n    control_s: {},\n    control_m: {},\n    control_l: {},\n    control_xl: {},\n    touch_min: {},\n    icon_s: {},\n    icon_m: {},\n    icon_l: {},\n    icon_xl: {},\n    bar_height: {},\n    switch: {},\n    slider_track: {},\n    slider_handle: {},\n    search_field: {},\n    list_row_min: {},\n}};\n",
        n("size.control.s"),
        n("size.control.m"),
        n("size.control.l"),
        n("size.control.xl"),
        n("size.touch_min"),
        n("size.icon.s"),
        n("size.icon.m"),
        n("size.icon.l"),
        n("size.icon.xl"),
        n("size.bar_height"),
        pair("size.switch"),
        n("size.slider_track"),
        pair("size.slider_handle"),
        n("size.search_field"),
        n("size.list_row_min"),
    )
    .unwrap_or_default();
}

fn type_scale(t: &Value, out: &mut String) {
    for (role, v) in object(t, "type.scale") {
        let a = v
            .as_array()
            .expect("type role is [size, line, weight, family]");
        let size = a[0].as_f64().expect("size");
        let line = a[1].as_f64().expect("line height");
        let weight = match a[2].as_u64().expect("weight") {
            400 => "Normal",
            500 => "Medium",
            600 => "Semibold",
            700 => "Bold",
            w => panic!("tokens.json: type.scale.{role} has unsupported weight {w}"),
        };
        let desc = a[3].as_str().expect("family description");
        let family = if desc.starts_with("Jost") {
            "Display"
        } else if desc.starts_with("JetBrains Mono") {
            "Mono"
        } else if desc.starts_with("Flex") {
            "Ui"
        } else {
            panic!("tokens.json: type.scale.{role} has unknown family `{desc}`")
        };
        // "+14% tracking" is letter spacing as a fraction of the size.
        let tracking = desc
            .split_whitespace()
            .find_map(|w| w.strip_prefix('+')?.strip_suffix('%')?.parse::<f64>().ok())
            .map_or(0.0, |p| p / 100.0);
        let uppercase = desc.contains("uppercase");
        writeln!(
            out,
            "pub(crate) const TYPE_{}: TypeStyle = TypeStyle {{ size: {}, line_height: {}, weight: Weight::{weight}, family: Family::{family}, tracking: {}, uppercase: {uppercase} }};",
            role.to_uppercase(),
            f(size),
            f(line),
            f(tracking),
        )
        .unwrap_or_default();
    }
    out.push('\n');
}

fn materials(t: &Value, out: &mut String) {
    let spec = |path: &str, xray: Option<bool>| {
        let opt = |key: &str| {
            get(t, path)
                .get(key)
                .and_then(Value::as_f64)
                .map_or_else(|| "1.0".to_owned(), f)
        };
        format!(
            "MaterialSpec {{ alpha: {}, blur: {}, saturate: {}, brightness: {}, xray: {xray:?} }}",
            f(num(t, &format!("{path}.alpha"))),
            f(num(t, &format!("{path}.blur"))),
            opt("saturate"),
            opt("brightness"),
        )
    };
    // xray: Mica samples the wallpaper only; Glass and Thick see the windows below.
    let rows = [
        ("MICA_DARK", spec("material.mica", Some(true))),
        ("GLASS_DARK", spec("material.glass", Some(false))),
        ("THICK_DARK", spec("material.thick_glass", Some(false))),
        ("MICA_LIGHT", spec("material.light.mica", Some(true))),
        ("GLASS_LIGHT", spec("material.light.glass", Some(false))),
        (
            "THICK_LIGHT",
            spec("material.light.thick_glass", Some(false)),
        ),
    ];
    for (name, s) in rows {
        writeln!(out, "pub(crate) const {name}: MaterialSpec = {s};").unwrap_or_default();
    }
    for (name, path) in [
        ("VEIL_DARK", "material.veil.dark"),
        ("VEIL_HI_DARK", "material.veil.dark_hi"),
        ("VEIL_LIGHT", "material.veil.light"),
        ("VEIL_HI_LIGHT", "material.veil.light_hi"),
    ] {
        writeln!(
            out,
            "pub(crate) const {name}: Color = {};",
            css_rgb(text(t, path))
        )
        .unwrap_or_default();
    }
    writeln!(
        out,
        "pub(crate) const MICA_ADAPTIVE_DARK: f32 = {};\npub(crate) const MICA_ADAPTIVE_LIGHT: f32 = {};\n",
        f(num(t, "material.mica_adaptive.dark")),
        f(num(t, "material.mica_adaptive.light")),
    )
    .unwrap_or_default();
}

/// CSS `X Y BLUR [SPREAD] rgb(...)` (px) to `(x, y, blur, spread, color)`.
fn css_shadow(s: &str) -> String {
    let (lengths, color) = s
        .split_once("rgb(")
        .unwrap_or_else(|| panic!("tokens.json: shadow `{s}` has no rgb() color"));
    let n: Vec<String> = lengths
        .split_whitespace()
        .map(|p| f(p.trim_end_matches("px").parse().expect("shadow length")))
        .collect();
    assert!(
        (3..=4).contains(&n.len()),
        "tokens.json: shadow `{s}` needs 3 or 4 lengths"
    );
    let spread = n.get(3).cloned().unwrap_or_else(|| "0.0".to_owned());
    format!(
        "ShadowToken {{ x: {}, y: {}, blur: {}, spread: {spread}, color: {} }}",
        n[0],
        n[1],
        n[2],
        css_rgb(&format!("rgb({color}"))
    )
}

fn elevation(t: &Value, out: &mut String) {
    for (name, key) in [
        ("SHADOW_FLOATING", "floating"),
        ("SHADOW_FLOATING_LARGE", "floating_large"),
        ("SHADOW_RAISED", "raised"),
        ("WINDOW_OUTLINE", "window_outline"),
    ] {
        writeln!(
            out,
            "pub(crate) const {name}: ShadowToken = {};",
            css_shadow(text(t, &format!("elevation.{key}")))
        )
        .unwrap_or_default();
    }
    out.push('\n');
}

fn motion(t: &Value, out: &mut String) {
    for key in [
        "spatial_fast",
        "spatial_default",
        "spatial_slow",
        "effects_fast",
        "effects_default",
        "effects_slow",
    ] {
        let a = get(t, &format!("motion.{key}"))
            .as_array()
            .expect("spring is [stiffness, damping_ratio]");
        writeln!(
            out,
            "pub(crate) const SPRING_{}: Spring = Spring {{ stiffness: {}, damping_ratio: {} }};",
            key.to_uppercase(),
            f(a[0].as_f64().expect("stiffness")),
            f(a[1].as_f64().expect("damping ratio")),
        )
        .unwrap_or_default();
    }
}
