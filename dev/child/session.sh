#!/bin/sh
# Native child session for real-machine testing: nested niri window on the
# user's desktop with triton inside, on a PRIVATE session bus so qs/DMS's
# org.freedesktop.Notifications claim doesn't leak in. Invoke under
# dbus-run-session (the mise task does this).
#
#   XDG_RUNTIME_DIR  private under target/child — triton's msg socket, lock
#                    pid and lock-notifs stay scoped to the child session.
#   HOME / config    the REAL ones: triton reads and regenerates the user's
#                    actual ~/.config/niri/triton + settings.toml — that is
#                    the point of this test.
#
#   TRITON_CMD       what niri spawns (default: debug triton, real services).
#                    --real-services means volume/brightness/power actions in
#                    the child act on the REAL system — the power menu really
#                    suspends. Pass TRITON_CMD="$PWD/target/debug/triton" for
#                    the safe fake backend.
set -eu
repo=${REPO:-$PWD}
TRITON_CMD=${TRITON_CMD:-"$repo/target/debug/triton --real-services"}

# Private runtime dir — Wayland resolves WAYLAND_DISPLAY against this, so make
# the display path absolute before overriding it.
RT="$repo/target/child/runtime"
rm -rf "$RT" && mkdir -p -m 700 "$RT"
case "${WAYLAND_DISPLAY:-wayland-1}" in
    /*) : ;;
    *)  export WAYLAND_DISPLAY="/run/user/$(id -u)/${WAYLAND_DISPLAY:-wayland-1}" ;;
esac
export XDG_RUNTIME_DIR="$RT"

# triton-lock spawns by name — prefer freshly built binaries over installed.
export PATH="$repo/target/debug:$PATH"

# Scratch niri config: defaults elsewhere, triton's generated includes, and
# just enough to drive the session (terminal, quit). Real HOME keeps the
# include pointing at the user's generated files — triton regenerates them.
CFG="$repo/target/child/config.kdl"
mkdir -p "$repo/target/child"
cat >"$CFG" <<KDL
// triton child-session config — generated by dev/child/session.sh
include optional=true "$HOME/.config/niri/triton/index.kdl"

binds {
    Mod+T { spawn "ghostty"; }
    Mod+Shift+E { quit; }
}
KDL

# `--` hands niri a spawn-at-startup command; it gets the child's own
# WAYLAND_DISPLAY/NIRI_SOCKET environment automatically.
exec niri -c "$CFG" -- $TRITON_CMD
